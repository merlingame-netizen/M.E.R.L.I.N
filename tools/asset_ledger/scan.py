def render_bible(graph: dict, prev: dict | None) -> str:
    s = graph["summary"]
    L: list[str] = []
    L.append(f"# Asset Ledger - Bible M.E.R.L.I.N.")
    L.append("")
    L.append(f"> Généré le {graph['generated']} par `tools/asset_ledger/scan.py` "
             f"(schema v{graph['schema_version']}). Source de vérité de l'inventaire d'assets. "
             "Ne PAS éditer à la main : régénéré à chaque scan.")
    L.append("")
    L.append("## Résumé")
    L.append("")
    L.append(f"- **Fichiers game-asset suivis** : {s['total_files']} ({human(s['total_bytes'])})")
    cc = s["status_counts"]
    L.append(f"- **Utilisés** : {cc.get('used',0) + cc.get('root',0) + cc.get('whitelisted',0)} "
             f"(dont racines {cc.get('root',0)}, whitelist {cc.get('whitelisted',0)})")
    L.append(f"- **Orphelins statiques (supprimables)** : {cc.get('orphan_static',0)} "
             f"→ {human(s['orphan_static_bytes'])} récupérables")
    L.append(f"- **Orphelins lore (à revoir, jamais auto-suppr.)** : {cc.get('orphan_lore',0)}")
    L.append(f"- **Références dynamiques (incertain)** : {cc.get('dynamic_uncertain',0)}")
    L.append("")
    L.append(f"- **Pression disque (regénérable/historique, hors graphe)** : "
             f"{human(s['disk_pressure_bytes'])} sur {len(graph['disk_pressure'])} dossiers")
    L.append("")

    # Disk pressure table (the real disk hogs)
    L.append("## Pression disque - dossiers regénérables / historiques")
    L.append("")
    L.append("Exclus du graphe de références (non-`res://` game content). Cible n°1 pour libérer le disque.")
    L.append("")
    L.append("| dossier | taille | regénérable | note |")
    L.append("|---|---:|:---:|---|")
    for d in graph["disk_pressure"][:25]:
        star = "" if d.get("size_complete", True) else " (≥)"
        L.append(f"| `{d['path']}` | {human(d['size_bytes'])}{star} | "
                 f"{'oui' if d['regenerable'] else 'NON'} | {d['note']} |")
    L.append("")

    # Top orphans
    orphans = [n for n in graph["nodes"] if n["status"] == "orphan_static"]
    orphans_sorted = sorted(orphans, key=lambda n: -n["size_bytes"])
    L.append("## Top orphelins statiques (candidats suppression sûre)")
    L.append("")
    if orphans_sorted:
        L.append("| chemin | taille | type | dernière modif | git |")
        L.append("|---|---:|---|---|:---:|")
        for n in orphans_sorted[:30]:
            L.append(f"| `{n['path']}` | {human(n['size_bytes'])} | {n['type']} | "
                     f"{n['mtime']} | {'yes' if n['git_tracked'] else '-'} |")
    else:
        L.append("*Aucun orphelin statique détecté.* 🎉")
    L.append("")

    # By category
    L.append("## Par catégorie")
    L.append("")
    by_type: dict[str, list] = defaultdict(list)
    for n in graph["nodes"]:
        by_type[n["type"]].append(n)
    for typ in sorted(by_type):
        items = by_type[typ]
        tb = sum(n["size_bytes"] for n in items)
        used = sum(1 for n in items if n["status"] in ("used", "root", "whitelisted"))
        orph = sum(1 for n in items if n["status"] == "orphan_static")
        L.append(f"### {typ} - {len(items)} fichiers, {human(tb)} "
                 f"(utilisés {used}, orphelins {orph})")
    L.append("")

    # Dynamic patterns to verify
    L.append("## Références dynamiques à vérifier manuellement")
    L.append("")
    if graph["dynamic_patterns"]:
        for p in graph["dynamic_patterns"]:
            L.append(f"- `{p}` (chemin calculé - les fichiers sous ce préfixe sont marqués incertains)")
    else:
        L.append("*Aucun préfixe dynamique détecté.*")
    L.append("")

    # Changelog delta
    L.append("## Changelog auto (delta depuis dernier scan)")
    L.append("")
    if prev:
        prev_paths = {n["path"]: n for n in prev.get("nodes", [])}
        cur_paths = {n["path"]: n for n in graph["nodes"]}
        added = [p for p in cur_paths if p not in prev_paths]
        removed = [p for p in prev_paths if p not in cur_paths]
        newly_orphan = [p for p, n in cur_paths.items()
                        if n["status"] == "orphan_static"
                        and prev_paths.get(p, {}).get("status") not in (None, "orphan_static")]
        L.append(f"- Depuis {prev.get('generated','?')}")
        L.append(f"- Ajoutés : {len(added)} · Retirés : {len(removed)} · Nouveaux orphelins : {len(newly_orphan)}")
        for p in added[:15]:
            L.append(f"  - `+` {p}")
        for p in removed[:15]:
            L.append(f"  - `-` {p}")
        for p in newly_orphan[:15]:
            L.append(f"  - `⚠ orphelin` {p}")
    else:
        L.append("*Premier scan - pas de delta.*")
    L.append("")
    L.append("---")
    L.append("*Régénérer : `python tools/asset_ledger/scan.py`. "
             "Nettoyage : `python tools/asset_ledger/cleanup.py`. "
             "Surveillance : `python tools/asset_ledger/watchdog.py`.*")
    return "\n".join(L) + "\n"



#!/usr/bin/env python3
"""
asset_ledger/scan.py - M.E.R.L.I.N. asset reference scanner.

Parses the whole Godot project tree and builds a reference graph of res:// game
assets: which files are reachable from the game roots (project.godot main_scene,
autoloads, enabled plugins, export presets) and which are orphans.

It ALSO reports "disk pressure": large regenerable / historical directories
(node_modules, .godot, build caches, tmp, ...) that are excluded from the game
graph but are the real disk hogs. This directly serves "libérer le disque".

Outputs (under docs/asset-ledger/):
  - graph.json  : machine-readable graph + disk pressure (consumed by cleanup.py / watchdog.py)
  - BIBLE.md    : human-readable "bible", kept up to date on every scan (with changelog delta)

Pure stdlib (Python 3.12). Content hash = blake2b (blake3 not installed).
No writes outside docs/asset-ledger/. Never deletes anything.
"""

# Top-level subtrees that are NOT part of the shipped Godot res:// game runtime:
# tooling, web demos, servers, native build workspaces, historical archives.
# Their source files are EXCLUDED from the game reference graph (never deletion
# candidates), but regenerable caches inside them (node_modules, build) are still
# captured as disk pressure and remain purgeable.
OUT_OF_SCOPE_TOP = {
    "tools", "server", "server-trellis", "web-demo", "external", "native",
    "ollama-proxy", "llm_simple", "archive",
}
# Any directory containing one of these marker files is a foreign subproject
# (node/native/python) whose sources are out of scope for the game graph.
SUBPROJECT_MARKERS = {"package.json", "CMakeLists.txt", "Cargo.toml"}

# Text files we parse for references.
PARSE_EXTS = {".gd", ".tscn", ".scn", ".tres", ".res", ".cfg", ".godot",
              ".import", ".json", ".md", ".txt", ".gdshader", ".shader", ".po"}

MAX_PARSE_BYTES = 4 * 1024 * 1024   # skip ref-parsing of files bigger than this
MAX_HASH_BYTES = 64 * 1024 * 1024   # skip content hash of files bigger than this

RES_RE = re.compile(r'res://[^"\'\)\s\]<>]+')
CLASS_NAME_RE = re.compile(r'^\s*class_name\s+([A-Za-z_][A-Za-z0-9_]*)', re.M)
# Dynamic path heuristics: a res:// literal containing a format/concat marker,
# OR a string prefix that is later concatenated. We capture the static prefix.
DYN_RE = re.compile(r'res://[^"\'\)]*?(?:%s|%d|%[0-9.]*[sdfx]|\{|\}|"\s*\+|\+\s*")')
IDENT_RE = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')


# --------------------------------------------------------------------------- #
# Helpers

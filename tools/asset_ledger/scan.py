def load_enabled_plugins(root: Path) -> set[str]:
    """Return posix dir prefixes of enabled editor plugins, e.g. 'addons/godot_mcp/'."""
    prefixes: set[str] = set()
    proj = root / "project.godot"
    if proj.exists():
        txt = proj.read_text(encoding="utf-8", errors="ignore")
        m = re.search(r'enabled=PackedStringArray\(([^)]*)\)', txt)
        if m:
            for p in RES_RE.findall(m.group(1)):
                # res://addons/<name>/plugin.cfg -> addons/<name>/
                rel = p[len("res://"):]
                parts = rel.split("/")
                if len(parts) >= 2 and parts[0] == "addons":
                    prefixes.add(f"addons/{parts[1]}/")
    return prefixes


def collect_roots(root: Path) -> tuple[set[str], list[str]]:
    """Return (root_res_paths, root_source_labels). Roots seed reachability."""
    roots: set[str] = set()
    labels: list[str] = []
    proj = root / "project.godot"
    if proj.exists():
        txt = proj.read_text(encoding="utf-8", errors="ignore")
        for p in RES_RE.findall(txt):
            roots.add(p)
        labels.append("project.godot")
    presets = root / "export_presets.cfg"
    if presets.exists():
        txt = presets.read_text(encoding="utf-8", errors="ignore")
        for p in RES_RE.findall(txt):
            roots.add(p)
        labels.append("export_presets.cfg")
    return roots, labels


def scan(root: Path) -> dict:
    tracked = git_tracked_set(root)
    enabled_plugins = load_enabled_plugins(root)
    root_res, root_labels = collect_roots(root)

    nodes: dict[str, dict] = {}          # res_path -> node
    class_to_res: dict[str, str] = {}    # class_name -> res_path
    static_edges: dict[str, set[str]] = defaultdict(set)   # from -> {to}
    dynamic_prefixes: set[str] = set()   # static prefixes of dynamic paths
    dynamic_sources: dict[str, set[str]] = defaultdict(set)  # prefix -> {from}
    file_texts: dict[str, str] = {}      # res_path -> text (parse cache for class refs)

    disk_pressure: list[dict] = []
    seen_regen_dirs: set[str] = set()
    oos_prefixes: set[str] = set()       # out-of-scope subtree prefixes (posix, trailing /)
    out_of_scope: list[dict] = []        # reported foreign subtrees (tooling/web/native)

    # ---- walk ----
    for dp, dn, fn in os.walk(root):
        rel_dir = Path(dp).relative_to(root).as_posix()

        # detect foreign subprojects (marker files) -> mark subtree out of scope,
        # but keep descending so regen caches inside (node_modules, build) are captured.
        if rel_dir != "." and rel_dir + "/" not in oos_prefixes:
            is_top_tool = "/" not in rel_dir and rel_dir in OUT_OF_SCOPE_TOP
            has_marker = any(m in fn for m in SUBPROJECT_MARKERS)
            if is_top_tool or has_marker:
                if not any(rel_dir.startswith(p) for p in oos_prefixes):
                    oos_prefixes.add(rel_dir + "/")
                    out_of_scope.append({
                        "path": rel_dir,
                        "reason": "top-level tooling/subproject" if is_top_tool else "foreign subproject (marker file)",
                    })
        in_scope = not any((rel_dir + "/").startswith(p) or rel_dir + "/" in oos_prefixes
                           for p in oos_prefixes)

        # prune + record regen dirs and ALL hidden (dot) dirs (never game assets)
        pruned = []
        for d in list(dn):
            is_regen = d in REGEN_DIR_NAMES
            is_dot = d.startswith(".")
            if is_regen or is_dot:
                full = Path(dp) / d
                rel = full.relative_to(root).as_posix()
                if rel not in seen_regen_dirs:
                    seen_regen_dirs.add(rel)
                    sz, complete = dir_size(full)
                    disk_pressure.append({
                        "path": rel,
                        "size_bytes": sz,
                        "size_complete": complete,
                        "regenerable": d not in (".git",),
                        "note": REGEN_NOTE.get(d, "hidden/tooling dir (not game content)"),
                    })
                pruned.append(d)
        for d in pruned:
            dn.remove(d)

        if not in_scope:
            continue  # foreign subtree: sources excluded from game graph (caches already captured above)

        for f in fn:
            ext = os.path.splitext(f)[1].lower()
            full = Path(dp) / f
            rel = full.relative_to(root).as_posix()
            res_path = "res://" + rel
            try:
                st = full.stat()
            except OSError:
                continue
            size = st.st_size

            if ext not in GAME_EXTS:
                continue  # non-game files ignored in the graph (still on disk)

            node = {
                "path": res_path,
                "rel": rel,
                "type": TYPE_BY_EXT.get(ext, "other"),
                "ext": ext,
                "size_bytes": size,
                "mtime": datetime.fromtimestamp(st.st_mtime, timezone.utc).strftime("%Y-%m-%d"),
                "hash": content_hash(full, size),
                "git_tracked": rel in tracked,
                "referenced_by": [],
                "reference_confidence": "none",
                "reachable": False,
                "status": "unknown",
            }
            nodes[res_path] = node

            if ext in PARSE_EXTS:
                txt = read_text(full, size)
                if txt:
                    file_texts[res_path] = txt
                    for cm in CLASS_NAME_RE.finditer(txt):
                        class_to_res[cm.group(1)] = res_path
                    for ref in RES_RE.findall(txt):
                        ref = ref.rstrip('.,;')
                        if ref != res_path:
                            static_edges[res_path].add(ref)
                    for dm in DYN_RE.finditer(txt):
                        frag = dm.group(0)
                        prefix = re.split(r'%|\{|"\s*\+|\+\s*"', frag)[0]
                        prefix = prefix.rsplit("/", 1)[0] + "/" if "/" in prefix[len("res://"):] else prefix
                        if len(prefix) > len("res://"):
                            dynamic_prefixes.add(prefix)
                            dynamic_sources[prefix].add(res_path)

    # ---- class_name usage edges (script referenced as a type/identifier) ----
    corpus_idents: set[str] = set()   # every identifier token across the codebase
    for src, txt in file_texts.items():
        idents = set(IDENT_RE.findall(txt))
        corpus_idents |= idents
        if not src.endswith(".gd"):
            continue
        for cname, target in class_to_res.items():
            if target == src:
                continue
            if cname in idents:
                static_edges[src].add(target)

    # ---- dynamic tagging: any node whose path starts with a dynamic prefix ----
    for res_path, node in nodes.items():
        for pref in dynamic_prefixes:
            if res_path.startswith(pref):
                node["reference_confidence"] = "dynamic"
                node["referenced_by"] = sorted(dynamic_sources.get(pref, []))
                break

    # ---- reachability BFS from roots ----
    # Seed: explicit roots + enabled-plugin trees + autoload/main scene already in root_res.
    reachable: set[str] = set()
    q: deque[str] = deque()
    for r in root_res:
        if r in nodes:
            reachable.add(r)
            q.append(r)
    # plugin trees are reachable as a unit
    for res_path, node in nodes.items():
        rel = node["rel"]
        for pref in enabled_plugins:
            if rel.startswith(pref):
                if res_path not in reachable:
                    reachable.add(res_path)
                    q.append(res_path)
                node["referenced_by"].append("enabled-plugin")
                break

    while q:
        cur = q.popleft()
        for nxt in static_edges.get(cur, ()):
            if nxt in nodes:
                nodes[nxt]["referenced_by"].append(cur)
                if nodes[nxt]["reference_confidence"] == "none":
                    nodes[nxt]["reference_confidence"] = "static"
                if nxt not in reachable:
                    reachable.add(nxt)
                    q.append(nxt)

    # ---- finalize node status ----
    # Code-like assets can be loaded by logical name (scene transitions, autoload
    # UI, ShaderMaterial by name). If such a file's stem (or its PascalCase form)
    # appears as an identifier anywhere, treat it as a soft/dynamic reference and
    # DO NOT flag it deletable: it goes to the manual-verify list instead.
    SOFT_REF_TYPES = {"scene", "script", "shader", "resource"}

    def soft_referenced(rel: str) -> bool:
        stem = os.path.splitext(os.path.basename(rel))[0]
        if len(stem) < 4:
            return False
        camel = "".join(p.capitalize() for p in stem.split("_"))
        return stem in corpus_idents or camel in corpus_idents

    counts = defaultdict(int)
    for res_path, node in nodes.items():
        rel = node["rel"]
        name = os.path.basename(rel)
        node["reachable"] = res_path in reachable
        node["referenced_by"] = sorted(set(node["referenced_by"]))[:20]

        whitelisted = (
            name in WHITELIST_NAMES
            or any(rel.startswith(p) for p in WHITELIST_PREFIXES)
            or rel.startswith("addons/")            # addon internals: never auto-delete
            or "/i18n/" in rel or rel.endswith(".translation")
        )
        if res_path in root_res:
            node["status"] = "root"
        elif whitelisted:
            node["status"] = "whitelisted"
        elif node["reachable"]:
            node["status"] = "used"
        elif node["reference_confidence"] == "dynamic":
            node["status"] = "dynamic_uncertain"
        elif node["type"] in SOFT_REF_TYPES and soft_referenced(rel):
            node["status"] = "dynamic_uncertain"     # name mentioned somewhere: verify manually
            node["reference_confidence"] = "dynamic"
        elif node["type"] == "lore":
            node["status"] = "orphan_lore"      # narrative: flag, never auto-delete
        else:
            node["status"] = "orphan_static"    # safe deletion candidate
        counts[node["status"]] += 1

    total_bytes = sum(n["size_bytes"] for n in nodes.values())
    orphan_static_bytes = sum(n["size_bytes"] for n in nodes.values() if n["status"] == "orphan_static")
    disk_pressure.sort(key=lambda d: d["size_bytes"], reverse=True)

    graph = {
        "schema_version": SCHEMA_VERSION,
        "generated": now_iso(),
        "root": str(root),
        "summary": {
            "total_files": len(nodes),
            "total_bytes": total_bytes,
            "status_counts": dict(counts),
            "orphan_static_bytes": orphan_static_bytes,
            "disk_pressure_bytes": sum(d["size_bytes"] for d in disk_pressure),
        },
        "dynamic_patterns": sorted(dynamic_prefixes),
        "out_of_scope": sorted(out_of_scope, key=lambda d: d["path"]),
        "disk_pressure": disk_pressure,
        "nodes": sorted(nodes.values(), key=lambda n: (-n["size_bytes"], n["path"])),
    }
    return graph



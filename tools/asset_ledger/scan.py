# Main
# --------------------------------------------------------------------------- #

def main() -> int:
    ap = argparse.ArgumentParser(description="M.E.R.L.I.N. asset reference scanner")
    ap.add_argument("--root", default=".", help="Godot project root (default: cwd)")
    ap.add_argument("--out", default="docs/asset-ledger", help="output dir")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    out_dir = (root / args.out) if not os.path.isabs(args.out) else Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    graph_path = out_dir / "graph.json"
    bible_path = out_dir / "BIBLE.md"

    prev = None
    if graph_path.exists():
        try:
            prev = json.loads(graph_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            prev = None

    if not args.quiet:
        print(f"[scan] scanning {root} ...", file=sys.stderr)
    graph = scan(root)

    graph_path.write_text(json.dumps(graph, ensure_ascii=False, indent=1), encoding="utf-8")
    bible_path.write_text(render_bible(graph, prev), encoding="utf-8")

    s = graph["summary"]
    if not args.quiet:
        print(f"[scan] {s['total_files']} game files, {human(s['total_bytes'])}", file=sys.stderr)
        print(f"[scan] orphan_static: {s['status_counts'].get('orphan_static',0)} "
              f"({human(s['orphan_static_bytes'])} recoverable)", file=sys.stderr)
        print(f"[scan] disk pressure: {human(s['disk_pressure_bytes'])} "
              f"across {len(graph['disk_pressure'])} regen dirs", file=sys.stderr)
        print(f"[scan] wrote {graph_path} + {bible_path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

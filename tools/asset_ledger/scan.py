def now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def human(n: int) -> str:
    f = float(n)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if f < 1024 or unit == "TB":
            return f"{f:.1f} {unit}" if unit != "B" else f"{int(f)} B"
        f /= 1024
    return f"{f:.1f} TB"


def content_hash(path: Path, size: int) -> str:
    if size > MAX_HASH_BYTES:
        return f"skip:{size}"
    h = hashlib.blake2b(digest_size=16)
    try:
        with open(path, "rb") as fh:
            for chunk in iter(lambda: fh.read(1024 * 256), b""):
                h.update(chunk)
    except OSError:
        return "unreadable"
    return h.hexdigest()


def read_text(path: Path, size: int) -> str:
    if size > MAX_PARSE_BYTES:
        return ""
    try:
        return path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return ""


def git_tracked_set(root: Path) -> set[str]:
    try:
        out = subprocess.run(
            ["git", "ls-files"], cwd=root, capture_output=True, text=True, timeout=120
        )
        if out.returncode == 0:
            return {line.strip().replace("\\", "/") for line in out.stdout.splitlines() if line.strip()}
    except (OSError, subprocess.SubprocessError):
        pass
    return set()


def dir_size(path: Path, budget_s: float = 8.0) -> tuple[int, bool]:
    """Sum file sizes under path. Returns (bytes, complete?). Time-bounded."""
    import time
    total = 0
    start = time.time()
    complete = True
    for dp, dn, fn in os.walk(path):
        if time.time() - start > budget_s:
            complete = False
            break
        for f in fn:
            try:
                total += os.path.getsize(os.path.join(dp, f))
            except OSError:
                pass
    return total, complete


